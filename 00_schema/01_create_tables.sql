CREATE TABLE students (
    student_id      NUMBER(6)        CONSTRAINT pk_students PRIMARY KEY,
    first_name      VARCHAR2(50)     NOT NULL,
    last_name       VARCHAR2(50)     NOT NULL,
    email           VARCHAR2(100)    NOT NULL,
    enrollment_year NUMBER(4)        NOT NULL,
    CONSTRAINT uq_students_email UNIQUE (email),
    CONSTRAINT ck_students_year  CHECK (enrollment_year BETWEEN 2000 AND 2100)
);

CREATE TABLE courses (
    course_id   NUMBER(6)        CONSTRAINT pk_courses PRIMARY KEY,
    course_name VARCHAR2(100)    NOT NULL,
    credits     NUMBER(2)        NOT NULL,
    max_seats   NUMBER(3)        NOT NULL,
    CONSTRAINT ck_courses_credits   CHECK (credits BETWEEN 1 AND 10),
    CONSTRAINT ck_courses_maxseats  CHECK (max_seats BETWEEN 1 AND 500)
);

CREATE TABLE enrollments (
    enrollment_id   NUMBER(8)     CONSTRAINT pk_enrollments PRIMARY KEY,
    student_id      NUMBER(6)     NOT NULL,
    course_id       NUMBER(6)     NOT NULL,
    grade           NUMBER(5,2),
    enrollment_date DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_enr_student FOREIGN KEY (student_id)
        REFERENCES students(student_id),
    CONSTRAINT fk_enr_course  FOREIGN KEY (course_id)
        REFERENCES courses(course_id),
    CONSTRAINT uq_enr_student_course UNIQUE (student_id, course_id),
    CONSTRAINT ck_enr_grade CHECK (grade IS NULL OR grade BETWEEN 0 AND 100)
);

CREATE TABLE audit_log (
    log_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action        VARCHAR2(20),
    table_name    VARCHAR2(30),
    rows_affected NUMBER,
    log_time      TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE SEQUENCE seq_enrollment_id START WITH 1000 INCREMENT BY 1;

CREATE INDEX idx_enr_course ON enrollments(course_id);
CREATE INDEX idx_enr_student ON enrollments(student_id);
